#!/usr/bin/env bash
# Installed in the container as /usr/local/sbin/cf-origin-firewall.
# Only lets Cloudflare's published IP ranges reach ports 80/443, so nobody can
# bypass Cloudflare by connecting to the home IP directly. Other ports are untouched.
#
# Refreshed daily by a systemd timer. If Cloudflare's list can't be fetched, the
# last good ruleset is loaded instead, and failing that, 80/443 stay fully closed.
set -euo pipefail

RULES=/etc/nftables.d/cf-origin.nft
mkdir -p "$(dirname "$RULES")"

fetch() {
    curl -fsS --max-time 20 "https://www.cloudflare.com/ips-$1" \
        | grep -E '^[0-9a-f.:]+/[0-9]+$' | paste -sd, -
}

if v4="$(fetch v4)" && v6="$(fetch v6)" && [[ -n $v4 && -n $v6 ]]; then
    cat > "$RULES.new" <<EOF
# Generated by cf-origin-firewall on $(date -Is), do not edit.
table inet cf_origin {}
delete table inet cf_origin
table inet cf_origin {
    set cf4 { type ipv4_addr; flags interval; elements = { $v4 } }
    set cf6 { type ipv6_addr; flags interval; elements = { $v6 } }
    chain input {
        type filter hook input priority filter; policy accept;
        iifname "lo" accept
        tcp dport { 80, 443 } ip saddr @cf4 accept
        tcp dport { 80, 443 } ip6 saddr @cf6 accept
        tcp dport { 80, 443 } drop
        udp dport 443 drop
    }
}
EOF
    nft -c -f "$RULES.new"
    mv "$RULES.new" "$RULES"
elif [[ -f $RULES ]]; then
    echo "could not fetch Cloudflare IP ranges, reloading last good ruleset" >&2
else
    echo "could not fetch Cloudflare IP ranges and no previous ruleset, closing 80/443" >&2
    cat > "$RULES" <<'EOF'
table inet cf_origin {}
delete table inet cf_origin
table inet cf_origin {
    chain input {
        type filter hook input priority filter; policy accept;
        iifname "lo" accept
        tcp dport { 80, 443 } drop
        udp dport 443 drop
    }
}
EOF
fi

nft -f "$RULES"
