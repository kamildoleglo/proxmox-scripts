#!/usr/bin/env bash
# Installed in the container as /usr/local/sbin/cloudflare-ips, run daily by a timer.
# Fetches Cloudflare's published IP ranges and applies them in two places:
#   - nftables: only those ranges may reach ports 80/443, so nobody can bypass
#     Cloudflare by connecting to the home IP directly (other ports are untouched).
#   - Caddy: those ranges are trusted to set CF-Connecting-IP (the real visitor IP).
#
# If the ranges can't be fetched, the last good copy is kept, and failing that,
# 80/443 stay fully closed.
set -euo pipefail

RULES=/etc/nftables.d/cf-origin.nft
CADDY_SNIPPET=/etc/caddy/cloudflare-ips.caddy
mkdir -p "$(dirname "$RULES")"

fetch() {
    curl -fsS --max-time 20 "https://www.cloudflare.com/ips-$1" | grep -E '^[0-9a-f.:]+/[0-9]+$'
}

if v4="$(fetch v4)" && v6="$(fetch v6)" && [[ -n $v4 && -n $v6 ]]; then
    cat > "$RULES.new" <<EOF
# Generated by cloudflare-ips on $(date -Is), do not edit.
table inet cf_origin {}
delete table inet cf_origin
table inet cf_origin {
    set cf4 { type ipv4_addr; flags interval; elements = { $(paste -sd, - <<<"$v4") } }
    set cf6 { type ipv6_addr; flags interval; elements = { $(paste -sd, - <<<"$v6") } }
    chain input {
        type filter hook input priority filter; policy accept;
        iifname "lo" accept
        tcp dport { 80, 443 } ip saddr @cf4 accept
        tcp dport { 80, 443 } ip6 saddr @cf6 accept
        tcp dport { 80, 443 } drop
        udp dport 443 drop
    }
}
EOF
    nft -c -f "$RULES.new"
    mv "$RULES.new" "$RULES"

    printf '# Generated by cloudflare-ips, do not edit.\ntrusted_proxies static %s\n' \
        "$(tr '\n' ' ' <<<"$v4 $v6")" > "$CADDY_SNIPPET.new"
    if ! cmp -s "$CADDY_SNIPPET.new" "$CADDY_SNIPPET"; then
        mv "$CADDY_SNIPPET.new" "$CADDY_SNIPPET"
        # --no-block: caddy.service is ordered after this unit, so waiting for the
        # reload here would deadlock. It runs as soon as this script exits.
        systemctl --no-block try-reload-or-restart caddy
    else
        rm -f "$CADDY_SNIPPET.new"
    fi
elif [[ -f $RULES ]]; then
    echo "could not fetch Cloudflare IP ranges, reloading last good copy" >&2
else
    echo "could not fetch Cloudflare IP ranges and no previous copy, closing 80/443" >&2
    cat > "$RULES" <<'EOF'
table inet cf_origin {}
delete table inet cf_origin
table inet cf_origin {
    chain input {
        type filter hook input priority filter; policy accept;
        iifname "lo" accept
        tcp dport { 80, 443 } drop
        udp dport 443 drop
    }
}
EOF
fi

# The Caddyfile imports this, so it must exist even before the first good fetch.
[[ -f $CADDY_SNIPPET ]] || echo "# No Cloudflare ranges fetched yet." > "$CADDY_SNIPPET"

nft -f "$RULES"
